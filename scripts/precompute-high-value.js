import { Readable } from "node:stream";
import { createGunzip } from "node:zlib";
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { readFootballPlays, aggregatePlays } from "../lib/sources/plays/precompute.js";
import { resolveSeason, publicSleeper } from "../lib/accounts/sleeper.js";
const state = await publicSleeper("/state/nfl"), season = resolveSeason(process.argv[2], state);
const output = process.argv[3] || ".data/precomputed";
const week = season < Number(state.season) ? 19 : season > Number(state.season) ? 1 : state.season_type === "regular" ? Number(state.week || state.leg || 1) : state.season_type === "post" ? 19 : 1;
const url = `https://github.com/nflverse/nflverse-data/releases/download/pbp/play_by_play_${season}.csv.gz`;
const response = await fetch(url, { signal: AbortSignal.timeout(180000) }); if (!response.ok) throw new Error(`PBP HTTP ${response.status}`);
const hash = createHash("sha256"), stream = Readable.fromWeb(response.body); let compressed = 0;
stream.on("data", chunk => { compressed += chunk.length; hash.update(chunk); if (compressed > 60000000) stream.destroy(new Error("PBP download bound exceeded")); });
const textStream = stream.pipe(createGunzip()); textStream.setEncoding("utf8");
const parsed = await readFootballPlays(textStream);
const result = aggregatePlays(parsed, { season, beforeWeek: week, provenance: { source: "nflverse_pbp", url, sha256: hash.digest("hex"), retrieved_at: new Date().toISOString(), derivation_version: "high-value-1", license: "nflverse public data; see docs/data-sources.md" } });
await mkdir(output, { recursive: true }); await writeFile(join(output, `${season}.json`), JSON.stringify(result));
console.log(JSON.stringify({ season, through_week: result.data_through_week, games: result.games.length, records: result.records.length, compressed_bytes: compressed, output_bytes: Buffer.byteLength(JSON.stringify(result)) }));
